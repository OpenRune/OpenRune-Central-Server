CREATE TABLE IF NOT EXISTS friend_chat_channels (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    owner_character_id INTEGER NULL REFERENCES account_characters(id) ON DELETE CASCADE,
    owner_name_key TEXT NOT NULL,
    display_name TEXT NOT NULL,
    channel_type SMALLINT NOT NULL DEFAULT 0,
    grouping_activity_id INTEGER NULL,
    suggested_world INTEGER NULL,
    min_join SMALLINT NOT NULL DEFAULT -1,
    min_talk SMALLINT NOT NULL DEFAULT -1,
    min_kick SMALLINT NOT NULL DEFAULT 7,
    loot_share_rank SMALLINT NOT NULL DEFAULT 0,
    coin_share_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    max_members INTEGER NOT NULL DEFAULT 100,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_friend_chat_type CHECK (channel_type BETWEEN 0 AND 1),
    CONSTRAINT chk_friend_chat_join_rank CHECK (min_join BETWEEN -1 AND 7),
    CONSTRAINT chk_friend_chat_talk_rank CHECK (min_talk BETWEEN -1 AND 7),
    CONSTRAINT chk_friend_chat_kick_rank CHECK (min_kick BETWEEN 2 AND 7),
    CONSTRAINT chk_friend_chat_loot_rank CHECK (loot_share_rank BETWEEN -1 AND 7),
    CONSTRAINT chk_friend_chat_max_members CHECK (max_members BETWEEN 1 AND 500),
    CONSTRAINT chk_friend_chat_official_owner CHECK (
        (channel_type = 0 AND owner_character_id IS NOT NULL AND grouping_activity_id IS NULL) OR
        (channel_type = 1 AND owner_character_id IS NULL AND grouping_activity_id IS NOT NULL)
    )
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_friend_chat_owner_character
    ON friend_chat_channels(owner_character_id)
    WHERE owner_character_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_friend_chat_owner_key_lower
    ON friend_chat_channels(lower(trim(owner_name_key)));
CREATE UNIQUE INDEX IF NOT EXISTS uq_friend_chat_grouping_activity
    ON friend_chat_channels(grouping_activity_id)
    WHERE grouping_activity_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS friend_chat_ranks (
    channel_id BIGINT NOT NULL REFERENCES friend_chat_channels(id) ON DELETE CASCADE,
    character_id INTEGER NOT NULL REFERENCES account_characters(id) ON DELETE CASCADE,
    rank SMALLINT NOT NULL,
    assigned_by_character_id INTEGER NULL REFERENCES account_characters(id) ON DELETE SET NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (channel_id, character_id),
    CONSTRAINT chk_friend_chat_explicit_rank CHECK (rank BETWEEN 1 AND 6)
);
CREATE INDEX IF NOT EXISTS idx_friend_chat_ranks_character ON friend_chat_ranks(character_id);

