-- Central-owned persistent clan state.
-- Interface state, formation sessions and clan-hall instances remain world-local.
-- Live channel presence is held in memory by Central and is not stored here.

CREATE TABLE IF NOT EXISTS clans (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name TEXT NOT NULL,
    owner_character_id INTEGER NOT NULL REFERENCES account_characters(id) ON DELETE RESTRICT,
    creation_time_minutes INTEGER NOT NULL,
    renamed_time_minutes INTEGER NOT NULL DEFAULT 0,
    allow_unaffined BOOLEAN NOT NULL DEFAULT TRUE,
    talk_rank INTEGER NOT NULL DEFAULT 0,
    kick_rank INTEGER NOT NULL DEFAULT 126,
    home_world INTEGER NOT NULL DEFAULT 255,
    interests_mask INTEGER NOT NULL DEFAULT 0,
    motif_top_icon INTEGER NOT NULL DEFAULT 126,
    motif_bottom_icon INTEGER NOT NULL DEFAULT 0,
    motif_colour INTEGER NOT NULL DEFAULT 0,
    recruit_min_combat INTEGER NOT NULL DEFAULT 0,
    recruit_min_skill_total INTEGER NOT NULL DEFAULT 0,
    recruit_min_quest_points INTEGER NOT NULL DEFAULT 0,
    recruit_iron_status INTEGER NOT NULL DEFAULT 0,
    hall_home_world_only BOOLEAN NOT NULL DEFAULT FALSE,
    hall_locked BOOLEAN NOT NULL DEFAULT FALSE,
    hall_player_count INTEGER NOT NULL DEFAULT 0,
    board_listed BOOLEAN NOT NULL DEFAULT FALSE,
    accepting_applications BOOLEAN NOT NULL DEFAULT FALSE,
    pending_abdication_requester_character_id INTEGER NULL REFERENCES account_characters(id) ON DELETE SET NULL,
    pending_abdication_requested_at BIGINT NULL,
    pending_abdication_due_at BIGINT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_clan_interests_mask CHECK (interests_mask BETWEEN 0 AND 65535),
    CONSTRAINT chk_clan_motif_top_icon CHECK (motif_top_icon BETWEEN 0 AND 28 OR motif_top_icon = 126),
    CONSTRAINT chk_clan_motif_bottom_icon CHECK (motif_bottom_icon BETWEEN 0 AND 28),
    CONSTRAINT chk_clan_motif_colour CHECK (motif_colour BETWEEN 0 AND 8),
    CONSTRAINT chk_clan_recruit_combat CHECK (recruit_min_combat BETWEEN 0 AND 127),
    CONSTRAINT chk_clan_recruit_skill_total CHECK (recruit_min_skill_total BETWEEN 0 AND 4095),
    CONSTRAINT chk_clan_recruit_quest_points CHECK (recruit_min_quest_points BETWEEN 0 AND 2047),
    CONSTRAINT chk_clan_recruit_iron_status CHECK (recruit_iron_status BETWEEN 0 AND 3),
    CONSTRAINT chk_clan_hall_player_count CHECK (hall_player_count BETWEEN 0 AND 2000)
    );

CREATE UNIQUE INDEX IF NOT EXISTS uq_clans_name_lower
    ON clans (lower(trim(name)));
CREATE INDEX IF NOT EXISTS idx_clans_owner_character
    ON clans (owner_character_id);
CREATE INDEX IF NOT EXISTS idx_clans_board_listed
    ON clans (board_listed, name)
    WHERE board_listed = TRUE;
CREATE INDEX IF NOT EXISTS idx_clans_pending_abdication_due
    ON clans (pending_abdication_due_at)
    WHERE pending_abdication_due_at IS NOT NULL;

CREATE TABLE IF NOT EXISTS clan_members (
    clan_id BIGINT NOT NULL REFERENCES clans(id) ON DELETE CASCADE,
    character_id INTEGER NOT NULL REFERENCES account_characters(id) ON DELETE CASCADE,
    rank INTEGER NOT NULL DEFAULT 0,
    join_rune_day INTEGER NOT NULL DEFAULT 0,
    muted BOOLEAN NOT NULL DEFAULT FALSE,
    extra_info INTEGER NOT NULL DEFAULT 0,
    last_seen_rune_day INTEGER NOT NULL DEFAULT 0,
    combat_level INTEGER NOT NULL DEFAULT 0,
    skill_total INTEGER NOT NULL DEFAULT 0,
    joined_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (clan_id, character_id),
    CONSTRAINT chk_clan_member_rank CHECK (rank BETWEEN 0 AND 126),
    CONSTRAINT chk_clan_member_combat_level CHECK (combat_level BETWEEN 0 AND 127),
    CONSTRAINT chk_clan_member_skill_total CHECK (skill_total BETWEEN 0 AND 4095)
    );

-- A permanent character may be affined with at most one clan.
CREATE UNIQUE INDEX IF NOT EXISTS uq_clan_members_character
    ON clan_members (character_id);
CREATE INDEX IF NOT EXISTS idx_clan_members_clan
    ON clan_members (clan_id);

CREATE TABLE IF NOT EXISTS clan_creation_participants (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    clan_id BIGINT NULL REFERENCES clans(id) ON DELETE SET NULL,
    character_id INTEGER NOT NULL REFERENCES account_characters(id) ON DELETE CASCADE,
    founder BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );
CREATE UNIQUE INDEX IF NOT EXISTS uq_clan_creation_participant
    ON clan_creation_participants (clan_id, character_id)
    WHERE clan_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_clan_creation_participants_character_day
    ON clan_creation_participants (character_id, created_at);

CREATE TABLE IF NOT EXISTS clan_bans (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    clan_id BIGINT NOT NULL REFERENCES clans(id) ON DELETE CASCADE,
    character_id INTEGER NULL REFERENCES account_characters(id) ON DELETE SET NULL,
    display_name TEXT NOT NULL,
    banned_by_character_id INTEGER NULL REFERENCES account_characters(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );
CREATE UNIQUE INDEX IF NOT EXISTS uq_clan_bans_name_lower
    ON clan_bans (clan_id, lower(trim(display_name)));
CREATE UNIQUE INDEX IF NOT EXISTS uq_clan_bans_character
    ON clan_bans (clan_id, character_id)
    WHERE character_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS clan_invites (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    clan_id BIGINT NOT NULL REFERENCES clans(id) ON DELETE CASCADE,
    invitee_character_id INTEGER NOT NULL REFERENCES account_characters(id) ON DELETE CASCADE,
    inviter_character_id INTEGER NOT NULL REFERENCES account_characters(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ NULL,
    consumed_at TIMESTAMPTZ NULL
    );
CREATE UNIQUE INDEX IF NOT EXISTS uq_clan_invites_pending
    ON clan_invites (clan_id, invitee_character_id)
    WHERE consumed_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_clan_invites_invitee_pending
    ON clan_invites (invitee_character_id, created_at DESC)
    WHERE consumed_at IS NULL;

CREATE TABLE IF NOT EXISTS clan_applications (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    -- Keep application history after a clan disbands so per-day counts remain correct.
    clan_id BIGINT NULL REFERENCES clans(id) ON DELETE SET NULL,
    applicant_character_id INTEGER NOT NULL REFERENCES account_characters(id) ON DELETE CASCADE,
    clan_name TEXT NOT NULL,
    applicant_combat_level INTEGER NOT NULL DEFAULT 0,
    applicant_skill_total INTEGER NOT NULL DEFAULT 0,
    applicant_quest_points INTEGER NOT NULL DEFAULT 0,
    applicant_iron_status INTEGER NOT NULL DEFAULT 0,
    applicant_skill_levels SMALLINT[] NOT NULL DEFAULT ARRAY[]::SMALLINT[],
    status SMALLINT NOT NULL DEFAULT 0,
    reviewer_character_id INTEGER NULL REFERENCES account_characters(id) ON DELETE SET NULL,
    applied_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_at TIMESTAMPTZ NULL,
    notified_at TIMESTAMPTZ NULL,
    CONSTRAINT chk_clan_application_status CHECK (status BETWEEN 0 AND 4),
    CONSTRAINT chk_clan_application_combat CHECK (applicant_combat_level BETWEEN 0 AND 126),
    CONSTRAINT chk_clan_application_skill_total CHECK (applicant_skill_total BETWEEN 0 AND 4095),
    CONSTRAINT chk_clan_application_quest_points CHECK (applicant_quest_points BETWEEN 0 AND 2047),
    CONSTRAINT chk_clan_application_iron_status CHECK (applicant_iron_status BETWEEN 0 AND 3)
    );
CREATE UNIQUE INDEX IF NOT EXISTS uq_clan_applications_pending
    ON clan_applications (clan_id, applicant_character_id)
    WHERE status = 0 AND clan_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_clan_applications_applicant_date
    ON clan_applications (applicant_character_id, applied_at);
CREATE INDEX IF NOT EXISTS idx_clan_applications_pending_by_clan
    ON clan_applications (clan_id, applied_at, id)
    WHERE status = 0 AND clan_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_clan_applications_unnotified
    ON clan_applications (applicant_character_id, reviewed_at, id)
    WHERE status IN (1, 2, 4) AND notified_at IS NULL;

CREATE TABLE IF NOT EXISTS clan_rank_titles (
    clan_id BIGINT NOT NULL REFERENCES clans(id) ON DELETE CASCADE,
    rank INTEGER NOT NULL,
    title_id INTEGER NOT NULL,
    PRIMARY KEY (clan_id, rank),
    CONSTRAINT chk_clan_rank_title_rank CHECK (rank BETWEEN 0 AND 124),
    CONSTRAINT chk_clan_rank_title_id CHECK (title_id BETWEEN 1 AND 265)
    );

-- Rank-gated permissions (stored as semantic rank, not client rank+2 encoding).
CREATE TABLE IF NOT EXISTS clan_permissions (
    clan_id BIGINT NOT NULL REFERENCES clans(id) ON DELETE CASCADE,
    setting_id INTEGER NOT NULL,
    minimum_rank INTEGER NOT NULL,
    PRIMARY KEY (clan_id, setting_id),
    CONSTRAINT chk_clan_permission_rank CHECK (minimum_rank BETWEEN -1 AND 128)
    );

-- Broadcast/notification settings are intentionally separate from administrative permissions.
CREATE TABLE IF NOT EXISTS clan_broadcast_settings (
    clan_id BIGINT NOT NULL REFERENCES clans(id) ON DELETE CASCADE,
    setting_id INTEGER NOT NULL,
    value INTEGER NOT NULL,
    PRIMARY KEY (clan_id, setting_id)
    );

-- Other integer clan settings that are neither rank permissions nor broadcast settings.
CREATE TABLE IF NOT EXISTS clan_settings (
    clan_id BIGINT NOT NULL REFERENCES clans(id) ON DELETE CASCADE,
    setting_id INTEGER NOT NULL,
    value INTEGER NOT NULL,
    PRIMARY KEY (clan_id, setting_id)
    );

CREATE TABLE IF NOT EXISTS clan_events (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    clan_id BIGINT NOT NULL REFERENCES clans(id) ON DELETE CASCADE,
    position INTEGER NOT NULL DEFAULT 0,
    event_date INTEGER NOT NULL,
    event_time INTEGER NOT NULL,
    duration_days INTEGER NOT NULL DEFAULT 0,
    world INTEGER NOT NULL DEFAULT 0,
    type INTEGER NOT NULL DEFAULT 0,
    subtype INTEGER NOT NULL DEFAULT 0,
    activity INTEGER NOT NULL DEFAULT 0,
    rank_plus_one INTEGER NOT NULL DEFAULT 0,
    creator_character_id INTEGER NULL REFERENCES account_characters(id) ON DELETE SET NULL,
    creator_display_name TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_clan_event_time CHECK (event_time BETWEEN 0 AND 1439),
    CONSTRAINT chk_clan_event_duration CHECK (duration_days BETWEEN 0 AND 14),
    CONSTRAINT chk_clan_event_world CHECK (world BETWEEN 0 AND 999)
    );
CREATE INDEX IF NOT EXISTS idx_clan_events_clan_position
    ON clan_events (clan_id, position, id);